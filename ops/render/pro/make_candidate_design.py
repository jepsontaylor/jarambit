"""Build a render design folder for an analysis-lane CANDIDATE that has not been promoted yet (no hand edits).

Every number is copied from the analysis artefacts: <wave>/<wave>_results.json (variant gates + mass + STEP sha16),
the variant build dir (ground_<v>.step + cad_revC9_<v>.json) and, for gates the wave did not re-solve
(identical handle / ring -> carried), the base design folder's README gate table. The output folder has the
same layout design_manifest.py reads for a released design, plus a 'Display label' line (e.g. RC5 CANDIDATE).

python3 make_candidate_design.py --results analysis/w86/w86_results.json --variant d --bld analysis/w85/bld/d \
    --base designs/switchback/C10a --label "RC5 CANDIDATE" --rev-tag W86-d --out <dir>
"""
import argparse, hashlib, json, re, shutil
from pathlib import Path

# gate -> (key in the wave results, note). V3 shows the converged V3R (min over roots, W86 rule of record).
MAP = {'V1': ('V1', 'a3 (W86)'), 'V3': ('V3R', 'serration-root V3R converged, min over T11-T14 roots (W86); V3 outside-support ' + '{V3_outside_support_finest}'),
       'V4': ('V4', 'v4r (W86)'), 'V6': ('V6', 'V6 sub, 3-term rule of record (W86)')}
CARRY = {'V2': 'record-only, tip identical to base', 'V5': 'ring identical to base',
         'V7': 'carried from base: handle identical (W86 scoring rule)'}


def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    for k in ('--results', '--variant', '--bld', '--base', '--out'): ap.add_argument(k, required=True)
    ap.add_argument('--label'); ap.add_argument('--rev-tag')
    ap.add_argument('--rev', help='promoted rev (e.g. C.10d); with --rc writes a released-RC README'); ap.add_argument('--rc'); ap.add_argument('--tag'); ap.add_argument('--step')
    a = ap.parse_args()
    R = json.loads(Path(a.results).read_text()); v = R['variants'][a.variant]
    assert v.get('all_pass') is True, f'{a.variant} is not all-pass in {a.results}'
    bld = Path(a.bld); step = Path(a.step) if a.step else bld / f'ground_{a.variant}.step'; cad = json.loads((bld / f'cad_revC9_{a.variant}.json').read_text())
    assert sha(step)[:16] == v['sha16'] == cad['sha256_16'], 'STEP sha16 disagrees between build, cad json and wave results'
    assert abs(cad['mass_g_Gr5'] - v['mass_g']) < 5e-4, 'mass disagrees'
    base = Path(a.base); BR = (base / 'README.md').read_text()
    rows = {m.group(1): m for m in re.finditer(r'^\|\s*(V\d)\s*\|\s*([^|]+?)\s*\|\s*\**([0-9.]+)\**[^|]*\|', BR, re.M)}
    rev = re.search(r'\bRev\s+([A-Z]\.[0-9]+[a-z]?)\b', BR.splitlines()[0]).group(1)
    sy = re.search(r'SF\s*=\s*([0-9.]+)\s*MPa\s*/\s*σ', BR).group(1); thr = re.search(r'\(≥\s*([0-9.]+)\)', BR).group(1)
    out = Path(a.out); (out / 'cad').mkdir(parents=True, exist_ok=True); (out / 'data').mkdir(exist_ok=True)
    shutil.copy2(step, out / 'cad' / step.name); shutil.copy2(bld / f'cad_revC9_{a.variant}.json', out / 'data' / f'cad_revC9_{a.variant}.json')
    gates, lines = {}, []
    for g in sorted(rows):
        case = rows[g].group(2)
        if g in MAP: val, note = float(v[MAP[g][0]]), MAP[g][1].format(**{k: x for k, x in v.items() if not isinstance(x, (dict, list))})
        elif g in CARRY: val, note = float(rows[g].group(3)), CARRY[g]
        else: continue
        gates[g] = val; lines.append(f'| {g} | {case} | {val:.3f} | | {note} |')
    lines.append(f"| V8 | mass | {v['mass_g']:.3f} g Gr5 | | |")
    (out / 'data' / 'candidate_gates.json').write_text(json.dumps({'candidate': {'gates': gates, 'mass_g': v['mass_g'],
        'source': {'results': str(a.results), 'results_sha256': sha(a.results), 'variant': a.variant, 'wave': R.get('wave')}}}, indent=1))
    if a.rev and a.rc: head = f"# SWITCHBACK Rev {a.rev} — release candidate ({a.rc}), tag {a.tag}\n"
    else: head = f"# SWITCHBACK Rev {rev} {a.rev_tag} — {a.label.lower()} (release candidate (rc5 candidate), NOT tagged)\n\nDisplay label: {a.rev_tag} {a.label}\n"
    (out / 'README.md').write_text(head + f"""
Generated by ops/render/pro/make_candidate_design.py from `{a.results}` (variant {a.variant}) — no hand edits.
Gates: SWITCHBACK C.9 human-max set, SF = {sy} MPa / σvM, all at (≥ {thr}).

| gate | case | SF | margin | note |
|---|---|---|---|---|
""" + '\n'.join(lines) + '\n')
    files = ['README.md', f'cad/{step.name}', f'data/cad_revC9_{a.variant}.json', 'data/candidate_gates.json']
    (out / 'SHA256SUMS').write_text(''.join(f'{sha(out / f)}  {f}\n' for f in files))
    print(json.dumps({'out': str(out), 'gates': gates, 'mass_g': v['mass_g']}))


if __name__ == '__main__':
    main()
